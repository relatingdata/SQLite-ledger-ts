// Docs: docs/naming-vocabulary.md § How it is measured
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const OUT = join(ROOT, 'docs', 'naming-vocabulary-analysis.md');
const SCAN = ['backend/src', 'frontend/src/lib'];
const SKIP = new Set(['node_modules', '.git', '.svelte-kit', 'dist']);

// The verb prefixes docs/naming-conventions-and-entity-glossary.md defines.
const DOCUMENTED_VERBS = new Set(['get', 'list', 'set', 'create', 'ensure', 'add', 'delete', 'remove', 'stage', 'post', 'complete', 'resolve', 'is', 'has', 'verify']);

// Groups of words that can name the same concept. A group with more than one
// word in use is a place where the code has not chosen a word.
const CONCEPTS: Record<string, string[]> = {
  'the thing held and sold': ['item', 'product', 'part', 'goods', 'sku', 'article', 'merchandise', 'stock', 'inventory'],
  'a place': ['location', 'warehouse', 'outlet', 'site', 'store', 'branch', 'shop', 'factory', 'depot'],
  'who we buy from': ['vendor', 'supplier'],
  'who we sell to': ['customer', 'client', 'buyer'],
  'people who work': ['employee', 'staff', 'worker', 'personnel'],
  'a request to buy or sell': ['order', 'quote'],
  'buying': ['purchase', 'buy', 'procure'],
  'selling': ['sale', 'sales', 'sell', 'sold'],
  'stock arriving': ['receive', 'receipt', 'received', 'receiving', 'intake'],
  'stock leaving': ['dispatch', 'ship', 'shipping', 'shipment', 'deliver', 'delivery'],
  'stock moving between places': ['transfer', 'move', 'redistribute', 'relocate', 'restock'],
  'stock lost': ['writeoff', 'spoil', 'spoilage', 'shrink', 'breakage', 'wastage'],
  'making things': ['assembly', 'assemble', 'bom', 'kit', 'produce', 'production', 'manufacture', 'build'],
  'a way of grouping': ['division', 'category', 'department', 'class', 'group', 'hierarchy', 'tier', 'dimension'],
  'how many': ['quantity', 'qty', 'count', 'units'],
  'reading': ['get', 'list', 'find', 'fetch', 'load', 'read', 'query', 'lookup', 'all'],
  'writing': ['set', 'update', 'save', 'put', 'upsert', 'modify', 'edit'],
  'making a record': ['create', 'add', 'new', 'make', 'insert', 'register'],
  'removing': ['delete', 'remove', 'drop', 'clear', 'erase'],
};

const SPELLINGS: [string, string][] = [['fulfil', 'fulfill'], ['labour', 'labor'], ['cancelled', 'canceled'], ['colour', 'color'], ['despatch', 'dispatch']];

function walk(dir: string, out: string[] = []): string[] {
  let names: string[];
  try { names = readdirSync(dir); } catch { return out; }
  for (const name of names) {
    if (SKIP.has(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith('.ts') && !name.endsWith('.test.ts')) out.push(full);
  }
  return out;
}

const words = (id: string): string[] => {
  const w = (id.match(/[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+/g) ?? []).map((x) => x.toLowerCase());
  const merged: string[] = [];
  for (let i = 0; i < w.length; i++) {
    if (w[i] === 'write' && w[i + 1] === 'off') { merged.push('writeoff'); i++; } else merged.push(w[i]);
  }
  return merged;
};

interface Id { name: string; file: string; kind: string }
const ids: Id[] = [];
const DECL: [RegExp, string][] = [
  [/^\s*export\s+(?:async\s+)?function\s+([A-Za-z_]\w*)/, 'function'],
  [/^\s*export\s+const\s+([A-Za-z_]\w*)/, 'const'],
  [/^\s*export\s+(?:interface|type|class|enum)\s+([A-Za-z_]\w*)/, 'type'],
];
for (const file of SCAN.flatMap((d) => walk(join(ROOT, d)))) {
  const rel = relative(ROOT, file).split(sep).join('/');
  for (const line of readFileSync(file, 'utf-8').split('\n')) {
    for (const [re, kind] of DECL) { const m = line.match(re); if (m) { ids.push({ name: m[1], file: rel, kind }); break; } }
  }
}
// The same name exported from backend and mirrored in the frontend is one name.
const unique = [...new Map(ids.map((i) => [i.name, i])).values()];
const fns = unique.filter((i) => i.kind === 'function' || (i.kind === 'const' && /^[a-z]/.test(i.name)));

const md: string[] = [];
md.push('# Naming Vocabulary: Analysis');
md.push('');
md.push('Generated by `scripts/analyze-vocabulary.ts` (`make analyze-vocabulary`) — never hand-edited, and deliberately **not** part of the Programmer\'s Manual, so the names in its tables are not counted as documentation by the coverage check.');
md.push('');
md.push(`Scanned ${unique.length} distinct exported names (${fns.length} functions and function-like constants) in ${SCAN.join(' and ')}.`);
md.push('');

md.push('## 1. First words of function names');
md.push('');
const verbCount = new Map<string, { n: number; ex: string[] }>();
for (const f of fns) {
  const v = words(f.name)[0] ?? '';
  const e = verbCount.get(v) ?? { n: 0, ex: [] };
  e.n++; if (e.ex.length < 3) e.ex.push(f.name);
  verbCount.set(v, e);
}
const sorted = [...verbCount.entries()].sort((a, b) => b[1].n - a[1].n);
md.push('**Defined** in `docs/naming-conventions-and-entity-glossary.md`:');
md.push('');
md.push('| Verb | Names | Examples |');
md.push('|---|---|---|');
for (const [v, e] of sorted.filter(([v]) => DOCUMENTED_VERBS.has(v))) md.push(`| \`${v}\` | ${e.n} | ${e.ex.map((x) => `\`${x}\``).join(', ')} |`);
md.push('');
md.push('**Not defined there** (in use, with no stated meaning):');
md.push('');
md.push('| First word | Names | Examples |');
md.push('|---|---|---|');
const undefinedVerbs = sorted.filter(([v]) => !DOCUMENTED_VERBS.has(v));
for (const [v, e] of undefinedVerbs.slice(0, 40)) md.push(`| \`${v}\` | ${e.n} | ${e.ex.map((x) => `\`${x}\``).join(', ')} |`);
if (undefinedVerbs.length > 40) md.push(`| *… ${undefinedVerbs.length - 40} more, each used fewer times* | | |`);
md.push('');

md.push('## 2. Which word does the code use for each concept?');
md.push('');
md.push('A concept with **more than one word in use** has no chosen word. Counts are distinct exported names containing the word.');
md.push('');
const split: string[] = [];
for (const [concept, variants] of Object.entries(CONCEPTS)) {
  const rows = variants.map((w) => {
    const hits = unique.filter((i) => words(i.name).includes(w));
    return { w, n: hits.length, ex: hits.slice(0, 3).map((h) => h.name) };
  }).filter((r) => r.n > 0).sort((a, b) => b.n - a.n);
  if (rows.length === 0) continue;
  if (rows.length > 1) split.push(concept);
  md.push(`### ${concept}${rows.length > 1 ? '  —  **' + rows.length + ' words in use**' : ''}`);
  md.push('');
  md.push('| Word | Names | Examples |');
  md.push('|---|---|---|');
  for (const r of rows) md.push(`| \`${r.w}\` | ${r.n} | ${r.ex.map((x) => `\`${x}\``).join(', ')} |`);
  md.push('');
}

md.push('## 3. Names that mix two words for one concept');
md.push('');
md.push('Single names that contain more than one word from the same concept group, so the name itself is inconsistent.');
md.push('');
const mixed: string[] = [];
for (const [concept, variants] of Object.entries(CONCEPTS)) {
  if (['reading', 'writing', 'making a record', 'removing', 'how many'].includes(concept)) continue;
  for (const i of unique) {
    const w = new Set(words(i.name));
    const found = variants.filter((v) => w.has(v));
    if (found.length > 1) mixed.push(`- \`${i.name}\` — ${concept}: ${found.join(' + ')}`);
  }
}
if (mixed.length === 0) md.push('None.'); else md.push(...mixed.slice(0, 40), ...(mixed.length > 40 ? [`- *… ${mixed.length - 40} more*`] : []));
md.push('');

md.push('## 4. Spelling variants');
md.push('');
md.push('| Spelling | Names using it | Alternative | Names using it |');
md.push('|---|---|---|---|');
for (const [a, b] of SPELLINGS) {
  const na = unique.filter((i) => words(i.name).includes(a)).length;
  const nb = unique.filter((i) => words(i.name).includes(b)).length;
  if (na + nb > 0) md.push(`| \`${a}\` | ${na} | \`${b}\` | ${nb} |`);
}
md.push('');

md.push('## 5. Accounting acronyms in names');
md.push('');
md.push('AR, AP, GL and P&L are written in capitals with their accounting meanings. Each row counts distinct names by how the acronym is cased inside them.');
md.push('');
md.push('| Acronym | Capitals (`AR`) | Title case (`Ar`) | Lower case (`ar`) |');
md.push('|---|---|---|---|');
const acronymCase = (acr: string): { upper: string[]; title: string[]; lower: string[] } => {
  const out = { upper: [] as string[], title: [] as string[], lower: [] as string[] };
  for (const i of unique) {
    for (const s of i.name.match(/[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+/g) ?? []) {
      if (s.toLowerCase() !== acr.toLowerCase()) continue;
      if (s === acr) out.upper.push(i.name);
      else if (s === acr[0] + acr.slice(1).toLowerCase()) out.title.push(i.name);
      else if (s === acr.toLowerCase()) out.lower.push(i.name);
    }
  }
  return out;
};
const acronymTotals: string[] = [];
for (const acr of ['AR', 'AP', 'GL', 'PL']) {
  const c = acronymCase(acr);
  const cell = (list: string[]): string => `${list.length}${list.length ? ' (' + list.slice(0, 2).map((x) => '`' + x + '`').join(', ') + ')' : ''}`;
  md.push(`| \`${acr}\` | ${cell(c.upper)} | ${cell(c.title)} | ${cell(c.lower)} |`);
  acronymTotals.push(`${acr}: ${c.upper.length} capitals / ${c.title.length} title-case / ${c.lower.length} lower`);
}
const profitAndLossNames = unique.filter((i) => /ProfitAndLoss/.test(i.name)).length;
md.push('');
md.push(`P&L cannot appear in a name; ${profitAndLossNames} names spell it \`ProfitAndLoss\`.`);
md.push('');

md.push('## 6. Retired words in the hand-written documentation');
md.push('');
md.push('"Goods" is retired in favour of "Items". The accounting phrases "Cost of Goods Sold", "goods sold" and "Goods and Services" are ignored. Generated reports, translations and the assembled manuals are excluded.');
md.push('');
md.push('| Where | The line |');
md.push('|---|---|');
const docsDir = join(ROOT, 'docs');
const skipDoc = /^(glossary|programmer-manual|user-manual\.md|naming-vocabulary-analysis|classification-neutrality-analysis|documentation-baseline-report|function-inventory)/;
let goodsTotal = 0; const goodsDocs = new Set<string>();
for (const name of readdirSync(docsDir).sort()) {
  if (!name.endsWith('.md') || skipDoc.test(name)) continue;
  readFileSync(join(docsDir, name), 'utf-8').split('\n').forEach((line, i) => {
    const cleaned = line.replace(/cost of goods( sold)?/gi, '').replace(/goods sold/gi, '').replace(/goods and services/gi, '');
    if (/\bgoods\b/i.test(cleaned)) { goodsTotal++; goodsDocs.add(name); md.push(`| ${name}:${i + 1} | ${line.trim().slice(0, 110).replace(/\|/g, '/')} |`); }
  });
}
if (goodsTotal === 0) md.push('| *(none)* | |');
md.push('');
const goodsNames = unique.filter((i) => words(i.name).includes('goods')).length;
md.push(`Exported names containing "goods": ${goodsNames}.`);
md.push('');

writeFileSync(OUT, md.join('\n') + '\n', 'utf-8');
console.log(`Wrote ${OUT}`);
console.log(`\nFirst words in use: ${sorted.length}; defined in the manual: ${sorted.filter(([v]) => DOCUMENTED_VERBS.has(v)).length}; not defined: ${undefinedVerbs.length}`);
console.log(`Function names covered by a defined verb: ${sorted.filter(([v]) => DOCUMENTED_VERBS.has(v)).reduce((n, [, e]) => n + e.n, 0)} of ${fns.length}`);
console.log(`Concept groups with more than one word in use: ${split.length}  (${split.join('; ')})`);
console.log(`Names mixing two words for one concept: ${mixed.length}`);
console.log(`Accounting acronyms in names, by casing: ${acronymTotals.join('; ')}`);
console.log(`Hand-written documents using "goods": ${goodsDocs.size} (${goodsTotal} occurrences); names containing it: ${goodsNames}`);
