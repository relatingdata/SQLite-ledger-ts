%% Small Erlang helper behind sqlite_cli.gleam. repo.hex.pm (where
%% sqlight's own NIF dependency, esqlite, is published) is not
%% reachable from this sandbox, so this engine drives a real sqlite3
%% CLI subprocess instead of a NIF — same real SQLite file, same real
%% transactions, just one process spawn per script instead of an
%% in-process C call. "Simplest possible" extends to the plumbing,
%% not only the schema.
-module(sqlite_cli_ffi).
-export([run_script/2, write_file/2, unique_int/0, now_iso/0]).

%% Runs every statement in the file at ScriptPath against the
%% database at DbPath in ONE sqlite3 invocation (-bail: stop at the
%% first error). Both paths are trusted, filesystem-safe strings
%% generated by sqlite_cli.gleam itself — NEVER built from request
%% data — so plain shell concatenation here carries no injection
%% risk; all real request data instead goes into the SCRIPT's own
%% SQL text, escaped as a string literal by sqlite_cli.gleam before
%% it ever reaches this module.
%% A busy/lock timeout matters for real now that this engine is
%% pointed at sqlite-ledger-ts's own, real, shared entities.sqlite:
%% db.ts's better-sqlite3 connection and this CLI subprocess are two
%% genuinely separate SQLite clients against the SAME file, and SQLite
%% allows only one writer at a time — without one, the loser of a
%% close race gets an immediate "database is locked" instead of
%% briefly waiting its turn. `-cmd "PRAGMA busy_timeout=5000;"` was
%% tried first and rejected: that PRAGMA is itself a real query — it
%% prints its own set value ("5000") as an extra output line ahead of
%% everything else, silently shifting every row query.gleam's own
%% newline-based row splitting expects, confirmed directly by
%% comparing CLI output with and without it. `-cmd ".timeout 20000"`
%% (a real sqlite3 shell meta-command, not a SQL statement) sets the
%% exact same busy-wait behavior with no output of its own.
run_script(DbPath, ScriptPath) ->
    Cmd = "sqlite3 -bail -cmd \".timeout 20000\" " ++ binary_to_list(DbPath) ++ " < " ++ binary_to_list(ScriptPath) ++ " 2>&1",
    Port = erlang:open_port({spawn, Cmd}, [exit_status, binary]),
    collect(Port, <<>>).

collect(Port, Acc) ->
    receive
        {Port, {data, Data}} ->
            collect(Port, <<Acc/binary, Data/binary>>);
        {Port, {exit_status, 0}} ->
            {ok, Acc};
        {Port, {exit_status, _Code}} ->
            {error, Acc}
    end.

write_file(Path, Content) ->
    case file:write_file(Path, Content) of
        ok -> {ok, nil};
        {error, _Reason} -> {error, nil}
    end.

unique_int() ->
    erlang:unique_integer([positive]).

%% "YYYY-MM-DD HH:MM:SS" in UTC - plenty for entities.created_at's
%% own ORDER BY created_at DESC tiebreak (row_id is the real,
%% guaranteed tiebreak for two rows in the same second anyway).
now_iso() ->
    {{Y, Mo, D}, {H, Mi, S}} = calendar:universal_time(),
    Bin = io_lib:format("~4..0B-~2..0B-~2..0B ~2..0B:~2..0B:~2..0B", [Y, Mo, D, H, Mi, S]),
    unicode:characters_to_binary(Bin).
